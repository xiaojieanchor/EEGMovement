"""Incremental NeuraDock parser. Never assigns unverified electrode identities."""
from dataclasses import dataclass
import math
from collections import deque

def source_idle(connected_at,last_valid_at,now,timeout=5.):
    """A live TCP connection is not proof of a progressing ADC stream."""
    return now-(last_valid_at if last_valid_at is not None else connected_at)>=timeout

@dataclass
class Packet:
    timestamp: str
    sequence: int
    samples: list
    gap: int = 0
    discontinuity: bool = False

class StreamParser:
    def __init__(self, mode='bluetooth', max_buffer=262144, disabled_channels=()):
        self.mode=mode;self.max_buffer=max_buffer;self.buffer=b''
        self.disabled_channels=frozenset(disabled_channels)
        self.last_sequence=None;self.last_signature=None;self.pending_discontinuity=False
        self.transitions=deque(maxlen=32)
        self.recent_signatures=deque(maxlen=32)
        self.stats=dict(valid_packets=0,duplicates=0,missing_packets=0,parse_errors=0,nul_bytes=0,resets=0,overflows=0)

    def feed(self,data):
        self.stats['nul_bytes']+=data.count(b'\x00')
        self.buffer+=data.replace(b'\x00',b'')
        if len(self.buffer)>self.max_buffer:
            self.buffer=b'';self.stats['overflows']+=1;self.last_sequence=None;self.recent_signatures.clear();self.stats['resets']+=1;self.pending_discontinuity=True
            return []
        packets=[]
        while b'\n' in self.buffer:
            line,self.buffer=self.buffer.split(b'\n',1)
            if not line.strip():continue
            try:
                fields=line.decode('utf-8',errors='strict').strip().split(',')
                # Saved BT uses47 fields; current TCP also47; shorter42-field official stream is accepted.
                groups=5 if self.mode=='bluetooth' else 1
                expected=2+8*groups
                if len(fields)<expected:raise ValueError('short row')
                timestamp=fields[0]
                if ':' not in timestamp:raise ValueError('header/non-timestamp row')
                number=float(fields[1]);seq=int(number)
                if not math.isfinite(number) or number!=seq or not 0<=seq<=255:raise ValueError('sequence')
                values=[float(v) for v in fields[2:expected]]
                # A dead electrode must not discard the other physical channels.
                # Finite original values remain in the raw audit; only invalid
                # numbers on explicitly disabled inputs are replaced here.
                for i,v in enumerate(values):
                    if i%8 in self.disabled_channels and not math.isfinite(v):values[i]=0.
                if not all(math.isfinite(v) for v in values):raise ValueError('nonfinite sample')
                # Vendor HH:mm:ss is generated by the forwarding task, not ADC.
                # The same adjacent ADC packet can acquire another host stamp.
                signature=(seq,tuple(values))
                if signature in self.recent_signatures:
                    self.stats['duplicates']+=1;continue
                gap=0;discontinuity=self.pending_discontinuity
                if self.last_sequence is not None:
                    step=(seq-self.last_sequence)%256
                    if step!=1:self.transitions.append(dict(previous=self.last_sequence,sequence=seq,step=step,timestamp=timestamp,same_values=tuple(values)==self.last_signature[1]))
                    if step==0 or step>128:
                        discontinuity=True;self.stats['resets']+=1;self.recent_signatures.clear()
                    elif step>1:
                        gap=step-1;self.stats['missing_packets']+=gap;discontinuity=True
                self.last_sequence=seq;self.last_signature=signature;self.stats['valid_packets']+=1;self.pending_discontinuity=False
                self.recent_signatures.append(signature)
                samples=[values[i*8:i*8+7] for i in range(groups)]
                packets.append(Packet(timestamp,seq,samples,gap,discontinuity))
            except (ValueError,UnicodeError,OverflowError):self.stats['parse_errors']+=1
        return packets
