"""Own one Hub runtime before opening device, model or network resources."""
import os
import socket
from http.server import ThreadingHTTPServer
from pathlib import Path


class HubAlreadyRunning(RuntimeError):
    pass


class HubInstance:
    def __init__(self, path):
        self.path = Path(path)
        self.file = None

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        handle = self.path.open('a+b')
        if os.fstat(handle.fileno()).st_size == 0:
            handle.write(b'0')
            handle.flush()
        handle.seek(0)
        try:
            if os.name == 'nt':
                import msvcrt
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as error:
            handle.close()
            raise HubAlreadyRunning('中枢已在运行，跳过重复启动；请打开现有中枢页面') from error
        self.file = handle
        return self

    def __exit__(self, *exc):
        if self.file is not None:
            try:
                self.file.seek(0)
                if os.name == 'nt':
                    import msvcrt
                    msvcrt.locking(self.file.fileno(), msvcrt.LK_UNLCK, 1)
                else:
                    import fcntl
                    fcntl.flock(self.file.fileno(), fcntl.LOCK_UN)
            finally:
                self.file.close()
                self.file = None


class ExclusiveHubServer(ThreadingHTTPServer):
    # Windows SO_REUSEADDR can let independent servers share one listening
    # address: the UI may then reach a different Hub from EEG ingest.
    allow_reuse_address = False
    daemon_threads = True

    def server_bind(self):
        if os.name == 'nt':
            self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
        super().server_bind()
